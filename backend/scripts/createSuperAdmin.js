/**
 * Creates (or promotes) a Super Admin account.
 *
 * Easiest: run with no arguments and answer the prompts (no quoting needed):
 *   npm run create-admin
 *
 * Non-interactive:
 *   npm run create-admin -- --name "Site Admin" --email admin@example.com --password '...'
 *   (optionally --uri "mongodb+srv://..." to target a different database)
 *
 * Public sign-up can never create Super Admins; this script is the only way.
 */
import readline from "readline";
import mongoose from "mongoose";
import { env } from "../config/env.js";
import { User } from "../models/userSchema.js";

const arg = (name) => {
  const index = process.argv.indexOf(`--${name}`);
  return index > -1 ? process.argv[index + 1] : undefined;
};

const rl = readline.createInterface({ input: process.stdin, output: process.stdout });
const lines = rl[Symbol.asyncIterator]();
const ask = async (question, { hidden = false } = {}) => {
  process.stdout.write(question);
  if (hidden && process.stdin.isTTY) {
    // Don't echo what is typed (password).
    rl._writeToOutput = () => {};
  }
  const { value = "" } = await lines.next();
  rl._writeToOutput = (s) => process.stdout.write(s);
  if (hidden && process.stdin.isTTY) process.stdout.write("\n");
  return value.trim();
};

const describeHost = (uri) => {
  try {
    return new URL(uri.replace(/^mongodb(\+srv)?:/, "http:")).host || uri;
  } catch {
    return "(unrecognised connection string)";
  }
};

let uri = arg("uri");
let name = arg("name") || process.env.ADMIN_NAME;
let email = arg("email") || process.env.ADMIN_EMAIL;
let password = arg("password") || process.env.ADMIN_PASSWORD;
const interactive = !email || !password;

if (interactive) {
  console.log("\nCreate a PrimeBid Super Admin\n");
  if (!uri) {
    uri = await ask(
      `MongoDB connection string\n  (paste your Atlas string for the live site, or press Enter to use ${describeHost(env.mongoUri || "")} from config.env):\n> `
    );
  }
  if (!name) name = (await ask("Admin name (Enter for \"Super Admin\"): ")) || "Super Admin";
  if (!email) email = await ask("Admin email: ");
  if (!password) password = await ask("Admin password (min 8 characters, hidden): ", { hidden: true });
}
rl.close();

uri = (uri || env.mongoUri || "").trim().replace(/^["']|["']$/g, "");
name = (name || "Super Admin").trim();
email = (email || "").trim().toLowerCase();

if (!/^mongodb(\+srv)?:\/\//.test(uri)) {
  console.error("\n✖ That doesn't look like a MongoDB connection string (it should start with mongodb+srv://).");
  process.exit(1);
}
if (!/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
  console.error("\n✖ Please enter a valid email address.");
  process.exit(1);
}
if (!password || password.length < 8) {
  console.error("\n✖ Password must be at least 8 characters.");
  process.exit(1);
}
if (!process.env.JWT_SECRET_KEY) {
  // Not used for creating the user, but the model module expects it to exist.
  process.env.JWT_SECRET_KEY = "unused-for-admin-creation";
}

console.log(`\nConnecting to ${describeHost(uri)} ...`);
try {
  await mongoose.connect(uri, { dbName: env.dbName, serverSelectionTimeoutMS: 15000 });
} catch (error) {
  console.error(`✖ Could not connect to the database: ${error.message}`);
  if (/ENOTFOUND _mongodb\._tcp\.(?!cluster)/.test(error.message)) {
    console.error("  Tip: your password probably contains @ : / ? or # - reset it to an autogenerated one in Atlas.");
  } else if (/auth/i.test(error.message)) {
    console.error("  Tip: wrong username/password in the connection string.");
  } else if (/timed out|Server selection/i.test(error.message)) {
    console.error("  Tip: check Atlas Network Access allows 0.0.0.0/0.");
  }
  process.exit(1);
}

try {
  const existing = await User.findOne({ email }).select("+password");
  if (existing) {
    existing.role = "Super Admin";
    existing.password = password;
    await existing.save();
    console.log(`✔ Updated ${email}: role set to Super Admin and password reset.`);
  } else {
    await User.create({ userName: name, email, password, role: "Super Admin" });
    console.log(`✔ Created Super Admin ${email}. You can now log in on the site.`);
  }
} catch (error) {
  console.error("✖ Failed to create Super Admin:", error.message);
  process.exitCode = 1;
} finally {
  await mongoose.disconnect();
}
